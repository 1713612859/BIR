package com.zuno.bir.enums;

/**
 * 折扣类型枚举
 * 代表了不同类型的政府法定折扣资格。
 */
public enum DiscountType {
    /**
     * 老年人 (Senior Citizen)
     */
    SC,
    /**
     * 残疾人士 (Person with Disability)
     */
    PWD,
    /**
     * 国家运动员和教练 (National Athletes and Coaches)
     */
    NAAC,
    /**
     * 奥运会和残奥会奖牌得主 (Medal of Valor)
     */
    MOV,
    /**
     * 单亲父母 (Solo Parent)
     */
    SP,
    /**
     * 外交官 (Diplomatic)
     */
    DIPLOMATIC
}
